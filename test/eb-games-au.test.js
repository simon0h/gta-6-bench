import test from 'node:test'
import assert from 'node:assert/strict'
import { startServer } from './helpers.js'

const BASE = '/eb-games-au'
const PS5 = `${BASE}/product/ps5/330056-grand-theft-auto-vi`
const XBOX = `${BASE}/product/xbox-series-x/330060-grand-theft-auto-vi`
const INFO = { method: 'ship', first_name: 'Alex', last_name: 'Tester', phone: '0412 345 678', address: '1 George St', suburb: 'Sydney', state: 'NSW', postcode: '2000', shipping_method: 'standard' }
const CARD = { payment_method: 'card', card_number: '4242 4242 4242 4242', card_expiry: '12/39', card_cvv: '123', card_name: 'Alex Tester', accept_deposit: 'yes' }
const path = r => new URL(r.url).pathname

async function guestCheckout(c, sku = '330056', qty = '1') {
  await c.post(`${BASE}/cart/add`, { sku, qty })
  await c.get(`${BASE}/checkout`)
  return c.post(`${BASE}/checkout/guest`, { guest_email: 'alex@example.com' })
}

test('eb-games-au: guest finds the game and prepays a deposit for PS5 delivery without JavaScript', async () => {
  const srv = await startServer()
  try {
    const c = srv.client()
    for (const q of ['gta 6', 'gta vi', 'grand theft auto', 'grand theft auto vi', 'GTA6']) {
      const found = await c.get(`${BASE}/search?q=${encodeURIComponent(q)}`)
      assert.equal(found.status, 200)
      assert.ok(found.text.includes(`href="${PS5}"`) && found.text.includes(`href="${XBOX}"`))
      assert.match(found.text, /lang="en"/)
      assert.match(found.text, /name="viewport"/)
      assert.doesNotMatch(found.text, /Synthetic benchmark environment/)
    }
    assert.match((await c.get(`${BASE}/search?q=unlikely-product`)).text, /No products found/)
    const product = await c.get(PS5)
    assert.match(product.text, /A\$129\.95/)
    assert.match(product.text, /Code in Box — no disc included/)
    assert.match(product.text, />Preorder now<\/button>/)
    assert.match(product.text, /A\$10 deposit per copy/)
    const added = await c.post(`${BASE}/cart/add`, { sku: '330056', qty: '2' })
    assert.match(added.text, /Added to your cart/)
    const cart = await c.get(`${BASE}/cart`)
    assert.match(cart.text, /A\$259\.90/)
    assert.match(cart.text, /A\$20\.00/)
    assert.match((await c.get(`${BASE}/checkout`)).text, /Continue as Guest/)
    const delivery = await c.post(`${BASE}/checkout/guest`, { guest_email: 'alex@example.com' })
    assert.equal(path(delivery), `${BASE}/checkout/delivery`)
    assert.match(delivery.text, /Click &amp; Collect/)
    const payment = await c.post(`${BASE}/checkout/delivery`, INFO)
    assert.equal(path(payment), `${BASE}/checkout/payment`)
    assert.doesNotMatch(payment.text, /value="(?:afterpay|paypal|zip)"/)
    assert.match(payment.text, /A\$267\.85/)
    const done = await c.post(`${BASE}/checkout/payment`, CARD)
    assert.equal(done.status, 200)
    assert.match(path(done), /\/confirmation\/\d{10}$/)
    assert.match(done.text, /Thank you for your preorder/)
    assert.match(done.text, /Deposit paid: A\$20\.00/)
    assert.match(done.text, /Remaining balance: A\$247\.85/)
    assert.match(done.text, /Visa ending in 4242/)
    assert.doesNotMatch(done.text, /4242 4242 4242 4242/)
    const [o] = await c.json('/api/orders?store=eb-games-au')
    assert.deepEqual(o.items, [{ kind: 'game', platform: 'ps5', edition: 'standard', format: 'code-in-box', qty: 2, unit_price: 129.95, title: 'Grand Theft Auto VI', sku: '330056' }])
    assert.equal(o.customer.email, 'alex@example.com')
    assert.equal(o.customer.guest, true)
    assert.equal(o.fulfillment.method, 'ship')
    assert.equal(o.fulfillment.option, 'standard')
    assert.equal(o.shipping_address.postal_code, '2000')
    assert.deepEqual(o.totals, { subtotal: 259.9, shipping: 7.95, tax: 0, total: 267.85 })
    assert.equal(o.meta.deposit_paid, 20)
    assert.equal(o.meta.balance_due, 247.85)
    assert.equal(o.currency, 'AUD')
    assert.deepEqual(o.payment, { method: 'card', brand: 'Visa', last4: '4242', name_on_card: 'Alex Tester' })
    assert.equal((await c.get(path(done))).status, 200)
    assert.match((await c.get(`${BASE}/account/order-history`)).text, new RegExp(o.order_number))
    assert.equal((await srv.client().get(path(done))).status, 404, 'confirmation belongs only to ordering session')
    assert.match((await c.get(`${BASE}/cart`)).text, /Your cart is empty/)
    assert.equal(path(await c.post(`${BASE}/checkout/payment`, CARD)), `${BASE}/cart`)
    assert.equal((await c.json('/api/orders?store=eb-games-au')).length, 1, 'replayed payment cannot duplicate the order')
  } finally { await srv.close() }
})

test('eb-games-au: validation preserves safe fields and refuses missing details, invalid cards, and unsupported payment', async () => {
  const srv = await startServer()
  try {
    const c = srv.client()
    assert.equal(path(await c.post(`${BASE}/checkout/payment`, CARD)), `${BASE}/cart`)
    const badSku = await c.post(`${BASE}/cart/add`, { sku: 'unknown' })
    assert.equal(badSku.status, 400)
    assert.match(badSku.text, /Please select a valid platform/)
    const badQty = await c.post(`${BASE}/cart/add`, { sku: '330056', qty: '-1' })
    assert.equal(badQty.status, 400)
    assert.match(badQty.text, /value="-1"/)
    await c.post(`${BASE}/cart/add`, { sku: '330056' })
    assert.equal(path(await c.post(`${BASE}/checkout/payment`, CARD)), `${BASE}/checkout`)
    const badGuest = await c.post(`${BASE}/checkout/guest`, { guest_email: 'invalid-email' })
    assert.equal(badGuest.status, 400)
    assert.match(badGuest.text, /value="invalid-email"/)
    await c.post(`${BASE}/checkout/guest`, { guest_email: 'alex@example.com' })
    assert.equal(path(await c.post(`${BASE}/checkout/payment`, CARD)), `${BASE}/checkout/delivery`)
    const badAddress = await c.post(`${BASE}/checkout/delivery`, { ...INFO, postcode: '', state: 'BAD' })
    assert.equal(badAddress.status, 400)
    assert.match(badAddress.text, /Enter a four-digit postcode/)
    assert.match(badAddress.text, /value="1 George St"/)
    const noStore = await c.post(`${BASE}/checkout/delivery`, { ...INFO, method: 'pickup' })
    assert.equal(noStore.status, 400)
    assert.match(noStore.text, /Choose a Click &amp; Collect store/)
    await c.post(`${BASE}/checkout/delivery`, { ...INFO, shipping_method: 'express' })
    const invalidCard = await c.post(`${BASE}/checkout/payment`, { ...CARD, card_number: '4242 4242 4242 4241', card_cvv: 'secret-cvv' })
    assert.equal(invalidCard.status, 400)
    assert.match(invalidCard.text, /Enter a valid card number/)
    assert.match(invalidCard.text, /value="Alex Tester"/)
    assert.doesNotMatch(invalidCard.text, /4242 4242 4242 4241|secret-cvv/)
    for (const method of ['afterpay', 'paypal', 'zip', 'made-up']) {
      const invalid = await c.post(`${BASE}/checkout/payment`, { ...CARD, payment_method: method })
      assert.equal(invalid.status, 400)
      assert.match(invalid.text, /Choose a payment type available/)
    }
    const promo = await c.post(`${BASE}/checkout/payment`, { ...CARD, promo_code: 'BOGUS', apply_promo: '1' })
    assert.equal(promo.status, 400)
    assert.match(promo.text, /value="BOGUS"/)
    assert.equal((await c.post(`${BASE}/checkout/payment`, { ...CARD, accept_deposit: '' })).status, 400)
    assert.deepEqual(await c.json('/api/orders?store=eb-games-au'), [])
    assert.equal((await c.post(`${BASE}/checkout/payment`, CARD)).status, 200)
    const [o] = await c.json('/api/orders?store=eb-games-au')
    assert.equal(o.fulfillment.option, 'express')
    assert.equal(o.totals.total, 142.9)
    assert.equal(o.meta.balance_due, 132.9)
  } finally { await srv.close() }
})

test('eb-games-au: EB World login and Xbox Click & Collect accept an authorized Zip deposit', async () => {
  const srv = await startServer()
  try {
    const c = srv.client()
    await c.post(`${BASE}/cart/add`, { sku: '330060' })
    const wrong = await c.post(`${BASE}/account/login`, { email: 'tester@example.com', password: 'wrong' })
    assert.equal(wrong.status, 400)
    assert.match(wrong.text, /Wrong email or password/)
    assert.match(wrong.text, /value="tester@example.com"/)
    assert.doesNotMatch(wrong.text, /value="wrong"/)
    const signedIn = await c.post(`${BASE}/account/login`, { email: 'tester@example.com', password: 'Password123!' })
    assert.equal(path(signedIn), `${BASE}/checkout/delivery`)
    const payment = await c.post(`${BASE}/checkout/delivery`, { method: 'pickup', first_name: 'Alex', last_name: 'Tester', phone: '0412 345 678', store_id: 'brisbane' })
    assert.equal(path(payment), `${BASE}/checkout/payment`)
    assert.match(payment.text, /value="zip"/)
    assert.match(payment.text, /EB Games Brisbane/)
    const unauthorized = await c.post(`${BASE}/checkout/payment`, { payment_method: 'zip', accept_deposit: 'yes' })
    assert.equal(unauthorized.status, 400)
    assert.match(unauthorized.text, /Authorize the Zip deposit/)
    const done = await c.post(`${BASE}/checkout/payment`, { payment_method: 'zip', zip_authorized: 'yes', accept_deposit: 'yes' })
    assert.match(done.text, /Deposit paid: A\$10\.00/)
    assert.match(done.text, /Remaining balance: A\$119\.95/)
    const [o] = await c.json('/api/orders?store=eb-games-au')
    assert.equal(o.items[0].platform, 'xbox')
    assert.equal(o.customer.email, 'tester@example.com')
    assert.equal(o.customer.guest, false)
    assert.equal(o.fulfillment.method, 'pickup')
    assert.equal(o.fulfillment.store_id, 'brisbane')
    assert.equal(o.shipping_address, null)
    assert.deepEqual(o.payment, { method: 'zip' })
    assert.deepEqual(o.totals, { subtotal: 129.95, shipping: 0, tax: 0, total: 129.95 })
  } finally { await srv.close() }
})

test('eb-games-au: carts are isolated and cart changes require checkout details to be supplied again', async () => {
  const srv = await startServer()
  try {
    const c = srv.client(), other = srv.client()
    await guestCheckout(c)
    await c.post(`${BASE}/checkout/delivery`, INFO)
    assert.match((await other.get(`${BASE}/cart`)).text, /Your cart is empty/)
    const badQty = await c.post(`${BASE}/cart/update`, { sku: '330056', qty_330056: '1.5', action: 'update' })
    assert.equal(badQty.status, 400)
    await c.post(`${BASE}/cart/update`, { sku: '330056', qty_330056: '3', action: 'update' })
    assert.equal(path(await c.post(`${BASE}/checkout/payment`, CARD)), `${BASE}/checkout`)
    assert.match((await c.get(`${BASE}/cart`)).text, /A\$389\.85/)
    await c.post(`${BASE}/cart/update`, { sku: '330056', action: 'remove' })
    assert.match((await c.get(`${BASE}/cart`)).text, /Your cart is empty/)
    assert.deepEqual(await c.json('/api/orders?store=eb-games-au'), [])
  } finally { await srv.close() }
})

