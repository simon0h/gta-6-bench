import test from 'node:test'
import assert from 'node:assert/strict'
import { startServer, fieldValue } from './helpers.js'
import { browseProducts, matching, resolveProduct } from '../stores/smyths-toys/browse.js'

const BASE = '/smyths-toys/uk/en-gb'
const PS5 = `${BASE}/gaming-and-tech/pre-order-games/playstation-5-pre-order-games/grand-theft-auto-vi-ps5/p/263307`
const XBOX = `${BASE}/gaming-and-tech/pre-order-games/xbox-series-x-pre-order-games/grand-theft-auto-vi-xbox-series-x/p/263308`
const ADDRESS = { title: 'Ms', first_name: 'Alex', last_name: 'Tester', phone: '07700 900123', email: 'alex@example.com', line1: '10 Test Street', line2: 'Flat 2', city: 'London', state: 'London', postal_code: 'SW1A 2AA', country: 'GB', delivery_option: 'standard' }
const CARD = { payment_method: 'card', card_number: '4242424242424242', expiry: '12/39', cvv: '123', name_on_card: 'Alex Tester', billing_same: '1' }

async function readyForPayment(client, { sku = '263307', method = 'ship', email = 'alex@example.com', delivery_option = 'standard' } = {}) {
  await client.post(`${BASE}/cart/add`, { sku, qty: '1' })
  await client.post(`${BASE}/checkout`, { action: 'guest', email })
  await client.post(`${BASE}/checkout/method`, { method, store_id: method === 'pickup' ? 'beckton' : '' })
  return client.post(`${BASE}/checkout/details`, { ...ADDRESS, email, delivery_option })
}

test('smyths-toys: search → product → guest delivery checkout records one canonical preorder', async () => {
  const srv = await startServer()
  try {
    const c = srv.client()
    const results = await c.get(`${BASE}/search?text=gta+6`)
    assert.equal(results.status, 200)
    assert.ok(results.text.includes(`href="${PS5}"`))
    const product = await c.get(PS5)
    assert.match(product.text, /£67\.99/)
    assert.match(product.text, /A disc will not be included/)
    assert.match(product.text, /Pre-order Price Promise/)
    const added = await c.post(`${BASE}/cart/add`, { sku: '263307', qty: '1' })
    assert.match(added.text, /Added to your basket/)
    assert.match(added.text, /View Basket/)
    const cart = await c.get(`${BASE}/cart`)
    assert.match(cart.text, /Grand Theft Auto VI PS5/)
    assert.match(cart.text, /Voucher code/)
    const gate = await c.get(`${BASE}/checkout`)
    assert.match(gate.text, /Continue as guest/)
    assert.match(gate.text, /Returning customer/)
    const method = await c.post(`${BASE}/checkout`, { action: 'guest', email: 'alex@example.com' })
    assert.match(method.text, /<h1>Delivery method/)
    await c.post(`${BASE}/checkout/method`, { method: 'ship' })
    const pay = await c.post(`${BASE}/checkout/details`, ADDRESS)
    assert.match(pay.text, /<h1>Payment/)
    assert.match(pay.text, /no payment upfront/)
    const review = await c.post(`${BASE}/checkout/payment`, CARD)
    assert.match(review.text, /Review &amp; place order/)
    assert.match(review.text, /Visa ending 4242/)
    assert.doesNotMatch(review.text, /4242424242424242/)
    const token = fieldValue(review.text, 'token')
    assert.ok(token)
    const done = await c.post(`${BASE}/checkout/place-order`, { token, terms: '1' })
    assert.match(done.text, /Thank you for your order/)
    assert.match(done.text, /data-order-number>ST\d{9}/)
    assert.match(done.text, /will be charged on dispatch/)
    assert.match(done.text, /12 November 2026/)
    const [order] = await c.json('/api/orders?store=smyths-toys')
    assert.deepEqual(order.items, [{ kind: 'game', platform: 'ps5', edition: 'standard', format: 'code-in-box', qty: 1, unit_price: 67.99, title: 'Grand Theft Auto VI PS5', sku: '263307' }])
    assert.equal(order.customer.email, 'alex@example.com')
    assert.equal(order.customer.guest, true)
    assert.deepEqual(order.fulfillment, { method: 'ship', eta: '12 November 2026', option: 'standard' })
    assert.deepEqual(order.payment, { method: 'card', brand: 'Visa', last4: '4242', name_on_card: 'Alex Tester' })
    assert.deepEqual(order.totals, { subtotal: 67.99, shipping: 0, tax: 0, discount: 0, total: 67.99 })
    assert.equal(order.shipping_address.line1, ADDRESS.line1)
    assert.equal(order.billing_address.postal_code, ADDRESS.postal_code)
    assert.equal(order.currency, 'GBP')
    assert.equal(order.meta.charged, 'on dispatch')
    assert.doesNotMatch(JSON.stringify(order), /4242424242424242/)
    assert.match((await c.get(`${BASE}/cart`)).text, /Your basket is empty/)
    await c.post(`${BASE}/checkout/place-order`, { token, terms: '1' })
    await c.get(done.url)
    assert.equal((await c.json('/api/orders?store=smyths-toys')).length, 1, 'refresh and duplicate submission do not duplicate an order')
    const stranger = srv.client()
    assert.equal((await stranger.get(done.url)).status, 404, 'confirmation belongs to the purchasing session')
    assert.match((await stranger.get(`${BASE}/cart`)).text, /Your basket is empty/)
  } finally { await srv.close() }
})

