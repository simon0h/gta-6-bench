test('smyths-toys: validation, checkout guards and changed basket prevent invalid or stale orders', async () => {
  const srv = await startServer()
  try {
    const c = srv.client()
    assert.match((await c.post(`${BASE}/checkout/place-order`, { terms: '1' })).url, /\/cart$/)
    const unavailable = await c.post(`${BASE}/cart/add`, { sku: 'ultimate-pc', qty: '1' })
    assert.equal(unavailable.status, 400)
    assert.match(unavailable.text, /select a platform/)
    assert.equal((await c.post(`${BASE}/cart/add`, { sku: '263307', qty: '-1' })).status, 400)
    await c.post(`${BASE}/cart/add`, { sku: '263307', qty: '1' })
    assert.match((await c.post(`${BASE}/checkout/payment`, CARD)).url, /\/checkout$/)
    await c.post(`${BASE}/checkout`, { action: 'guest', email: 'alex@example.com' })
    await c.post(`${BASE}/checkout/method`, { method: 'ship' })
    const badAddress = await c.post(`${BASE}/checkout/details`, { ...ADDRESS, postal_code: '12345' })
    assert.equal(badAddress.status, 400)
    assert.match(badAddress.text, /Enter a valid UK postcode/)
    assert.match(badAddress.text, /value="10 Test Street"/)
    assert.match(badAddress.text, /value="12345"/)
    await c.post(`${BASE}/checkout/details`, { ...ADDRESS, delivery_option: 'express' })
    const invalid = await c.post(`${BASE}/checkout/payment`, { ...CARD, card_number: '1234567890123456' })
    assert.equal(invalid.status, 400)
    assert.match(invalid.text, /Enter a valid card number/)
    assert.match(invalid.text, /value="Alex Tester"/)
    assert.doesNotMatch(invalid.text, /1234567890123456|value="123"/)
    assert.deepEqual(await c.json('/api/orders?store=smyths-toys'), [])
    const review = await c.post(`${BASE}/checkout/payment`, CARD)
    assert.match(review.text, /£69\.98/)
    const token = fieldValue(review.text, 'token')
    const terms = await c.post(`${BASE}/checkout/place-order`, { token })
    assert.equal(terms.status, 400)
    assert.match(terms.text, /Please agree/)
    assert.equal((await c.post(`${BASE}/checkout/place-order`, { token: 'forged', terms: '1' })).status, 400)
    await c.post(`${BASE}/cart/update`, { sku: '263307', 'qty-263307': '2', action: 'update' })
    const stale = await c.post(`${BASE}/checkout/place-order`, { token, terms: '1' })
    assert.match(stale.url, /\/checkout$/)
    assert.deepEqual(await c.json('/api/orders?store=smyths-toys'), [])
    assert.equal((await c.post(`${BASE}/cart/update`, { sku: '263307', 'qty-263307': '99' })).status, 400)
    await c.post(`${BASE}/cart/update`, { sku: '263307', action: 'remove' })
    assert.match((await c.get(`${BASE}/cart`)).text, /Your basket is empty/)
  } finally { await srv.close() }
})

