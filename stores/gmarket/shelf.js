const hash = s => { let n = 2166136261; for (const c of String(s)) n = Math.imul(n ^ c.codePointAt(0), 16777619); return n >>> 0 }
const round10 = n => Math.round(n / 10) * 10

export const shelf = Object.freeze(Object.entries(groups).flatMap(([dept, rows]) => rows.map(([code, brand, title, price, discount, sub, art, flags, extra = {}], i) => {
  const h = hash(code)
  const reviews = extra.reviews ?? (extra.sold !== undefined || h % 5 === 0 ? 0 : (h % 2400) + 3)
  const sold = extra.sold ?? (reviews ? reviews * (3 + (h % 9)) : (h % 40))
  return Object.freeze({
    code, brand, title, price, discount,
    list: discount ? round10(price / (1 - discount / 100)) : price,
    dept, sub, art, flags,
    star: flags.includes('s'), free: flags.includes('f') || price >= 30000, today: flags.includes('t') || flags.includes('s'),
    emart: flags.includes('e'), deal: flags.includes('d'), homeshopping: flags.includes('h'), preorder: flags.includes('n') && /예약/.test(title),
    sat: reviews ? (extra.sat ?? 86 + (h % 14)) : null, reviews, sold,
    options: extra.options || null, game: extra.game || null,
    seller: flags.includes('e') ? '이마트몰' : brand ? `${brand} 공식스토어` : ['G마켓 셀러', '스마일배송관', '모두의쇼핑'][h % 3],
    rank: i,
    path: `/Item?goodscode=${code}`,
  })
})))

export const shelfByCode = new Map(shelf.map(p => [p.code, p]))
export const inDept = (code, sub = 0) => shelf.filter(p => p.dept === code && (!sub || p.sub === sub))
// G마켓 랭크순 is the default order: what sells, weighted by satisfaction.
export const rankScore = p => p.sold * (p.sat || 80) / 100 + (p.star ? 500 : 0)
export const best = (list = shelf) => [...list].sort((a, b) => rankScore(b) - rankScore(a))
export const brandsOf = list => [...new Set(list.map(p => p.brand).filter(Boolean))].sort((a, b) => a.localeCompare(b, 'ko'))
